/**
 * Build step, runs after prerender.mjs: writes dist/security-headers.conf, an nginx snippet with the headers the gap audit
 * asked for (C1): a Content-Security-Policy and a Permissions-Policy.
 *
 * It is generated, not hand-written, because the policy allows the one inline script in index.html (the preloader failsafe)
 * by its hash, and the hash changes whenever that script does. nginx includes the file from the built site, so a new build
 * always ships a matching policy:
 *
 *     include /var/www/soldirectory/apps/web/dist/security-headers.conf;
 *
 * The Content-Security-Policy starts as Content-Security-Policy-Report-Only: the browser reports what it WOULD block in the
 * console without blocking anything. Browse the main pages, check the console for violations, fix or allow them, then set
 * CSP_ENFORCE=true for the build (or rename the header by hand) to switch it to enforcing.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const indexPath = path.join(dist, 'index.html');
if (!fs.existsSync(indexPath)) {
  console.error('[security-headers] dist/index.html not found: run `vite build` first.');
  process.exit(1);
}
const html = fs.readFileSync(indexPath, 'utf8');

// Every inline script that actually runs (JSON-LD blocks are data and are not subject to script-src).
const hashes = [];
for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
  if (/ld\+json/.test(m[1])) continue;
  // The browser reads the page with line endings normalised to \n, so the hash must be taken on that form.
  const body = m[2].split('\r\n').join('\n').split('\r').join('\n');
  hashes.push(`'sha256-${crypto.createHash('sha256').update(body).digest('base64')}'`);
}

const policy = [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(' ')}`.trim(),
  // React sets style attributes all over the app, and the preloader has an inline <style>.
  "style-src 'self' 'unsafe-inline'",
  // Listing logos come from each business's own website, so images may come from any https host.
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  // The map and address search use Mapbox. The API is on the same origin.
  "connect-src 'self' https://api.mapbox.com https://events.mapbox.com https://*.tiles.mapbox.com",
  "worker-src 'self' blob:",
  "child-src 'self' blob:",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'self'",
  'upgrade-insecure-requests',
].join('; ');

const header = process.env.CSP_ENFORCE === 'true' ? 'Content-Security-Policy' : 'Content-Security-Policy-Report-Only';
// The site uses the browser's speech synthesis (Read aloud) but no camera, microphone, location, payment or USB access.
const permissions = 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()';

const conf = [
  '# Generated by apps/web/scripts/security-headers.mjs on every web build. Do not edit.',
  `add_header ${header} "${policy}" always;`,
  `add_header Permissions-Policy "${permissions}" always;`,
  '',
].join('\n');

fs.writeFileSync(path.join(dist, 'security-headers.conf'), conf);
console.log(`[security-headers] wrote dist/security-headers.conf (${header}, ${hashes.length} inline script hash${hashes.length === 1 ? '' : 'es'}).`);
